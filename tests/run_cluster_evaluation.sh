#!/bin/bash
#SBATCH --job-name=neus_evaluation
#SBATCH --partition=gpu
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=32G
#SBATCH --time=06:00:00
#SBATCH --output=logs/%j_evaluation.out
#SBATCH --error=logs/%j_evaluation.err
#
# Smoke test + evaluation of the full pipeline on real data.
# Fill in the CONFIG block, then:   mkdir -p logs && sbatch tests/run_cluster_evaluation.sh
# Result: $OUT/results.md (Markdown tables for the README) + per-case CSVs.

set -euo pipefail
export PYTHONUNBUFFERED=1

# =============================== CONFIG ===================================
REPO="${REPO:-$(pwd)}"                       # repository root (sbatch from there)
CONDA_SH=/opt/miniconda3/etc/profile.d/conda.sh
TF_ENV=/path/to/tf_env                       # env with requirements/classification.txt
NNUNET_ENV=/path/to/nnunet_env               # env with requirements/segmentation.txt + vermis_height.txt

export nnUNet_raw=/path/to/nnUNet_raw
export nnUNet_preprocessed=/path/to/nnUNet_preprocessed
export nnUNet_results=/path/to/nnUNet_results

CEREBELLUM_DATASET=010                       # mid-sagittal cerebellum model (binary, 1 = cerebellum)
SKULL_DATASET=009                            # skull model; leave empty to skip
SKULL_LABEL=1                                # skull label value in the skull dataset
CONFIGURATION=2d
FOLDS=all

# Reviewer labels: CSV with image_path,user_label
#   PLANE_CSV: user_label in {mid_saggital, relevant_coronal, not_relevant}
#   INCL_CSV : user_label in {include, exclude} (optional)
PLANE_CSV=/path/to/review_results.csv
INCL_CSV=""
MAX_CLS_IMAGES=0                             # 0 = all labeled images

SSM_MODEL="$REPO/models/ssm/sagittal/pca_shape_model.npz"
LANDMARK_A=15
LANDMARK_B=60
MAX_HD95_MM=1.5

# Optional: measurements_summary.csv of an EARLIER pipeline run, to check
# how many measurements the old verticality check flagged as unreliable.
OLD_MEASUREMENTS=""
# ==========================================================================

OUT="$REPO/outputs/evaluation_$(date +%Y%m%d_%H%M)"
RESULTS="$OUT/results.md"
mkdir -p "$OUT"
cd "$REPO"
source "$CONDA_SH"

pad() { printf "%03d" "$((10#$1))"; }
dataset_dir() { find "$1" -maxdepth 1 -type d -name "Dataset$(pad "$2")_*" | head -n 1; }

CER_RAW=$(dataset_dir "$nnUNet_raw" "$CEREBELLUM_DATASET")
CER_MODEL=$(find "$(dataset_dir "$nnUNet_results" "$CEREBELLUM_DATASET")" -maxdepth 1 -type d -name "*__${CONFIGURATION}" | head -n 1)
echo "Cerebellum dataset: $CER_RAW"
echo "Cerebellum model  : $CER_MODEL"

{
    echo "## Results"
    echo
    echo "Generated by \`tests/run_cluster_evaluation.sh\` on $(date +%Y-%m-%d) (git $(git rev-parse --short HEAD 2>/dev/null || echo n/a))."
    echo
} > "$RESULTS"

# ------------------------------------------------------------------ 1. TF
echo "=== [1/5] Classification (TF env) ==="
conda activate "$TF_ENV"
python tests/smoke_test.py --stages classification --workdir "$OUT/smoke_classification" \
    | tee "$OUT/smoke_classification.log"

echo "### Classification" >> "$RESULTS"; echo >> "$RESULTS"
python tests/evaluate.py classifier --csv "$PLANE_CSV" \
    --model models/classifiers/mid_sagittal_classifier/model.keras --class-names not_mid_saggital mid_saggital \
    --label-map mid_saggital=mid_saggital relevant_coronal=not_mid_saggital not_relevant=not_mid_saggital \
    --max-images "$MAX_CLS_IMAGES" --name "Mid-sagittal classifier" --out "$RESULTS"
if [ -n "$INCL_CSV" ]; then
    python tests/evaluate.py classifier --csv "$INCL_CSV" \
        --model models/classifiers/incl_excl/cp.keras --class-names exclude include \
        --max-images "$MAX_CLS_IMAGES" --name "Include / exclude classifier" --out "$RESULTS"
fi
conda deactivate

# -------------------------------------------------------------- 2. nnU-Net
echo "=== [2/5] Smoke test segmentation + vermis (nnU-Net env) ==="
conda activate "$NNUNET_ENV"
python tests/smoke_test.py --stages segmentation vermis --nnunet-model "$CER_MODEL" --device cuda \
    --workdir "$OUT/smoke_segmentation" | tee "$OUT/smoke_segmentation.log"

echo "=== [3/5] nnU-Net predictions on the test sets ==="
nnUNetv2_predict -i "$CER_RAW/imagesTs" -o "$OUT/pred_cerebellum" \
    -d "$CEREBELLUM_DATASET" -c "$CONFIGURATION" -f $FOLDS
echo "### Segmentation (held-out test sets)" >> "$RESULTS"; echo >> "$RESULTS"
python tests/evaluate.py seg --pred-dir "$OUT/pred_cerebellum" --gt-dir "$CER_RAW/labelsTs" \
    --label 1 --name "Cerebellum / vermis (Dataset$(pad "$CEREBELLUM_DATASET"))" --out "$RESULTS"

if [ -n "$SKULL_DATASET" ]; then
    SKULL_RAW=$(dataset_dir "$nnUNet_raw" "$SKULL_DATASET")
    nnUNetv2_predict -i "$SKULL_RAW/imagesTs" -o "$OUT/pred_skull" \
        -d "$SKULL_DATASET" -c "$CONFIGURATION" -f $FOLDS
    python tests/evaluate.py seg --pred-dir "$OUT/pred_skull" --gt-dir "$SKULL_RAW/labelsTs" \
        --label "$SKULL_LABEL" --name "Skull (Dataset$(pad "$SKULL_DATASET"))" --out "$RESULTS"
fi

# ----------------------------------------------------------- 3. vermis
echo "=== [4/5] Vermis height: predicted vs. ground-truth segmentation ==="
for SRC_NAME in pred gt; do
    if [ "$SRC_NAME" = pred ]; then IN="$OUT/pred_cerebellum"; else IN="$CER_RAW/labelsTs"; fi
    python src/segmentation/make_vermis_labelmap.py --cerebellum-dir "$IN" \
        --output-dir "$OUT/vermis_$SRC_NAME/labelmaps" --largest-component
    python src/vermis_height/04_fit_pca.py --pca-model "$SSM_MODEL" \
        --input "$OUT/vermis_$SRC_NAME/labelmaps" --output-dir "$OUT/vermis_$SRC_NAME/fitted" \
        --max-hd95-mm "$MAX_HD95_MM"
    python src/vermis_height/06_measure_vermis.py \
        --fitted-landmarks-dir "$OUT/vermis_$SRC_NAME/fitted/fitted_landmarks" \
        --fit-results-csv "$OUT/vermis_$SRC_NAME/fitted/fit_results.csv" \
        --spacing-dir "$OUT/vermis_$SRC_NAME/labelmaps" \
        --labels-dir "$OUT/vermis_$SRC_NAME/labelmaps" \
        --output-dir "$OUT/vermis_$SRC_NAME/measurements" \
        --landmark-a "$LANDMARK_A" --landmark-b "$LANDMARK_B" --max-angle-deviation-deg 25
done
echo "### Vermis height" >> "$RESULTS"; echo >> "$RESULTS"
python tests/evaluate.py vermis --pred-csv "$OUT/vermis_pred/measurements/measurements_summary.csv" \
    --gt-csv "$OUT/vermis_gt/measurements/measurements_summary.csv" --out "$RESULTS"

python - "$OUT" "$MAX_HD95_MM" >> "$RESULTS" <<'EOF'
import sys, pandas as pd
out, thr = sys.argv[1], sys.argv[2]
print("| Shape model fit | fitted | HD95 ≤ %s mm | HD95 median (mm) |" % thr)
print("|---|---|---|---|")
for name in ("pred", "gt"):
    f = pd.read_csv(f"{out}/vermis_{name}/fitted/fit_results.csv")
    ok = f[f["success"] == True]
    good = int(ok["fit_quality_ok"].sum()) if "fit_quality_ok" in ok else len(ok)
    label = "nnU-Net segmentation" if name == "pred" else "ground-truth segmentation"
    print(f"| {label} | {len(ok)}/{len(f)} | {good}/{len(f)} | {ok['hd95_mm'].median():.3f} |")
print()
EOF

# ----------------------------------------------------------- 4. old run
echo "=== [5/5] Summary ==="
if [ -n "$OLD_MEASUREMENTS" ]; then
    python - "$OLD_MEASUREMENTS" <<'EOF' | tee -a "$OUT/old_measurements_check.txt"
import sys, pandas as pd
df = pd.read_csv(sys.argv[1])
n = len(df); r = int(df["measurement_reliable"].sum())
print(f"Earlier run: {r}/{n} measurements marked reliable by the OLD verticality check "
      f"({df['min_angle_from_vertical_deg'].median():.0f} deg median angle).")
print("If this is close to 0, the old check measured the angle against the wrong image axis.")
EOF
fi

grep -E "^\[(PASS|FAIL)" "$OUT"/smoke_*.log | sed 's/^/  /' || true
echo
echo "Results written to $RESULTS"
cat "$RESULTS"
